-- Adds runtime to sessions — which sandbox runtime hosts this session ("docker", "applevf", …).
--
-- Load bearing rather than informational: a node can offer more than one runtime, so Stop, Destroy,
-- and Exec have to route back to the driver that created the session. Without this column a restarted
-- node would not know which driver owns an existing session.
--
-- Nullable because DuckDB rejects ADD COLUMN with a constraint ("Adding columns with constraints not
-- yet supported"), the same limitation 0002 and 0003 hit. In practice the column is always populated:
-- Service.Create resolves the runtime before insert and the INSERT names the column explicitly, so only
-- rows predating this migration can be NULL. Those read back as "" and fall through to the node's
-- default runtime.
ALTER TABLE sessions ADD COLUMN runtime TEXT;
